import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { injectRoute } from "../src/injectors/route.js";
import { insertImport } from "../src/injectors/source.js";
import { injectSwagger } from "../src/injectors/swagger.js";
import { TEMPLATES_DIR } from "../src/lib/paths.js";

const read = (template: string, file: string) =>
    fs.readFileSync(path.join(TEMPLATES_DIR, template, "src", file), "utf-8");

const updated = (result: ReturnType<typeof injectRoute>): string => {
    if (result.status !== "updated") throw new Error(`expected update, got ${result.status}`);
    return result.content;
};

/** For assertions that don't care about line endings. */
const lf = (s: string) => s.replace(/\r\n/g, "\n");

/** routes.ts as generated by older templates: double quotes, no `.js`, CRLF. */
const legacyRoutes = [
    `import { Router } from "express";`,
    `import authRoute from "./app/modules/auth/auth.route";`,
    `import userRoute from "./app/modules/user/user.route";`,
    ``,
    `const appRouter = Router();`,
    ``,
    `const moduleRoutes = [`,
    `  { path: "/auth", route: authRoute },`,
    `  { path: "/user", route: userRoute },`,
    `];`,
    ``,
    `moduleRoutes.forEach((route) => appRouter.use(route.path, route.route));`,
    `export default appRouter;`,
    ``,
].join("\r\n");

describe("injectRoute", () => {
    it("matches the style of older projects (double quotes, no .js)", () => {
        const out = lf(updated(injectRoute(legacyRoutes, "order")));
        expect(out).toContain(`import orderRoute from "./app/modules/order/order.route";`);
        expect(out).toMatch(/\{ path: "\/user", route: userRoute \},\n {2}\{ path: "\/order", route: orderRoute \},\n\];/);
    });

    it.each(["mongoose", "prisma"])("matches the %s template style (single quotes, .js)", (template) => {
        const out = updated(injectRoute(read(template, "routes.ts"), "order"));
        expect(out).toContain(`import orderRoute from './app/modules/order/order.route.js';`);
        expect(out).toContain(`  { path: '/order', route: orderRoute },\n];`);
    });

    it("places the import after the last import", () => {
        const out = lf(updated(injectRoute(legacyRoutes, "order")));
        const lines = out.split("\n");
        expect(lines[3]).toContain("orderRoute");
        expect(lines[4]).toBe("");
    });

    it("is idempotent", () => {
        const once = updated(injectRoute(read("prisma", "routes.ts"), "order"));
        expect(injectRoute(once, "order")).toEqual({ status: "unchanged" });
    });

    it("reports failure when moduleRoutes is missing", () => {
        expect(injectRoute(`import x from "y";\n`, "order").status).toBe("failed");
    });
});

describe("injectSwagger", () => {
    it.each(["mongoose", "prisma"])("registers docs in the %s template", (template) => {
        const out = lf(updated(injectSwagger(read(template, "swaggerOptions.ts"), "order")));
        expect(out).toMatch(/import \{ orderSwaggerDocs \} from ['"]\.\/app\/modules\/order\/order\.swagger(\.js)?['"];/);
        // new entry uses the same indentation as existing ones, then the block closes
        expect(out).toMatch(/\n( +)\.\.\.\w+SwaggerDocs,\n\1\.\.\.orderSwaggerDocs,\n {4}\},/);
    });

    it("is idempotent", () => {
        const once = updated(injectSwagger(read("prisma", "swaggerOptions.ts"), "order"));
        expect(injectSwagger(once, "order")).toEqual({ status: "unchanged" });
    });
});

describe("insertImport", () => {
    it("handles multi-line imports", () => {
        const src = `import {\n  a,\n  b,\n} from "x";\n\nconst y = 1;\n`;
        expect(insertImport(src, `import z from "z";`)).toBe(
            `import {\n  a,\n  b,\n} from "x";\nimport z from "z";\n\nconst y = 1;\n`,
        );
    });

    it("prepends when there are no imports", () => {
        expect(insertImport("const y = 1;\n", `import z from "z";`)).toBe(`import z from "z";\nconst y = 1;\n`);
    });
});

describe("line endings", () => {
    it("preserves CRLF files", () => {
        const crlf = legacyRoutes;
        expect(crlf).toContain("\r\n");
        const out = updated(injectRoute(crlf, "order"));
        expect(out).toContain("orderRoute");
        expect(out.replace(/\r\n/g, "")).not.toContain("\n");
    });
});
